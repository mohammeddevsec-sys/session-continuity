import crypto from 'node:crypto';
const H=x=>crypto.createHash('sha256').update(JSON.stringify(x)).digest('hex');
const sign=(k,x)=>crypto.sign(null,Buffer.from(JSON.stringify(x)),k).toString('base64');
const verify=(k,x,s)=>crypto.verify(null,Buffer.from(JSON.stringify(x)),k,Buffer.from(s,'base64'));
const root=H({type:'CONTINUITY_ROOT',session:'S1',subject:'U1',issuer:'I1'});
const signer=crypto.generateKeyPairSync('ed25519');
const makeProof=branch=>{const body={schema:'continuity-proof.v1.1',continuity_root:root,sequence:3,parent_hash:'P2',state_hash:H({branch}),decision_hash:H({decision:'ALLOW'}),issued_at:'2026-01-01T00:00:00.000Z',signer_key_id:'S1',policy_fingerprint_sha256:'P1'};body.continuity_hash=H(body);return {body,signature:sign(signer.privateKey,body)}};
const proofA=makeProof('A');
const proofB=makeProof('B');
const A={domain:'DOMAIN-A',keyId:'W-A',keys:crypto.generateKeyPairSync('ed25519')};
const B={domain:'DOMAIN-B',keyId:'W-B',keys:crypto.generateKeyPairSync('ed25519')};
const receipt=(w,p)=>{const body={schema:'witness-receipt.v1.1',continuity_root:root,sequence:3,observed_proof_hash:H(p.body),continuity_hash:p.body.continuity_hash,witness_domain_id:w.domain,witness_key_id:w.keyId,witness_head_hash:p.body.continuity_hash,result:'ADVANCED'};return {body,signature:sign(w.keys.privateKey,body)}};
const rA1=receipt(A,proofA);
const rA2=receipt(A,proofB);
const rB=receipt(B,proofA);
const verifyReceipt=(w,r)=>{if(r.body.witness_domain_id!==w.domain)return 'TRUST_DOMAIN_MISMATCH';if(r.body.witness_key_id!==w.keyId)return 'WITNESS_KEY_MISMATCH';return verify(w.keys.publicKey,r.body,r.signature)?'VALID':'WITNESS_RECEIPT_TAMPERED'};
const sameDomainFork=(a,b)=>a.body.witness_domain_id===b.body.witness_domain_id&&a.body.witness_key_id===b.body.witness_key_id&&a.body.continuity_root===b.body.continuity_root&&a.body.sequence===b.body.sequence&&a.body.continuity_hash!==b.body.continuity_hash?'EQUIVOCATION_FORK':'NOT_EQUIVOCATION';
const crossDomain=(a,b)=>a.body.witness_domain_id!==b.body.witness_domain_id&&a.body.continuity_root===b.body.continuity_root&&a.body.sequence===b.body.sequence&&a.body.continuity_hash!==b.body.continuity_hash?'NOT_GLOBAL_EQUIVOCATION':'CROSS_DOMAIN_ASSERTION_INVALID';
const a1=verifyReceipt(A,rA1);
const a2=verifyReceipt(A,rA2);
const b=verifyReceipt(B,rB);
const wrong=verifyReceipt(B,rA1);
const fork=sameDomainFork(rA1,rA2);
const cross=crossDomain(rA2,rB);
console.log('=== GAP 8 :: CROSS-WITNESS-DOMAIN V2 ===');
console.log('DOMAIN_A_RECEIPT='+a1);
console.log('DOMAIN_A_CONFLICTING_RECEIPT='+a2);
console.log('DOMAIN_B_RECEIPT='+b);
console.log('CROSS_DOMAIN_TRUST_REJECTED='+(wrong==='TRUST_DOMAIN_MISMATCH'?'PASS':'FAIL'));
console.log('SAME_DOMAIN_FORK='+fork);
console.log('CROSS_DOMAIN_DIFFERING_OBSERVATION='+cross);
console.log('GLOBAL_NON_EQUIVOCATION_CLAIM='+(cross==='NOT_GLOBAL_EQUIVOCATION'?'ABSENT':'FAIL'));
console.log('GAP8_REFERENCE_RESULT='+([a1==='VALID',a2==='VALID',b==='VALID',wrong==='TRUST_DOMAIN_MISMATCH',fork==='EQUIVOCATION_FORK',cross==='NOT_GLOBAL_EQUIVOCATION'].every(Boolean)?'PASS':'FAIL'));
