import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { provisionSigningAuthority } from "../../src/evidence/signing-authority.js";
import { createBindingKey, createSignedPresentation } from "../../src/core/proof-of-possession.js";
import { createSecureSessionState, issueChallenge } from "../../src/core/durable-secure-session-state.js";
import { createDurableTrustStore } from "../../src/evidence/durable-trust-store.js";
import { createOidcSessionAnchor } from "../../src/adapters/oidc-session-adapter.js";
import { executeSessionContinuityDecision } from "../../src/product/session-continuity-decision.js";
const root=fs.mkdtempSync(path.join(os.tmpdir(),"fork-baseline-"));
const authority=provisionSigningAuthority(path.join(root,"authority"),{label:"fork-baseline"});
const trust=createDurableTrustStore(authority.trustRoot);
const key=createBindingKey();
const claims={sub:"fork-user",iss:"https://issuer.example",sid:"fork-session",auth_time:"2026-09-15T03:00:00.000Z",aud:"fork-client"};
const anchorBase=createOidcSessionAnchor({verifiedClaims:claims,clientId:"fork-client",deviceId:"device-A"});
const anchor={...anchorBase,publicKeySpkiBase64:key.publicKeySpkiBase64,publicKeyFingerprintSha256:key.publicKeyFingerprint};
const source=path.join(root,"state-p1");
const branchA=path.join(root,"branch-A");
const branchB=path.join(root,"branch-B");
const state=createSecureSessionState(source,60000);
const now1=1700000000000;
const ch1=issueChallenge(state,anchor.sessionId,now1,60000);
const s1=createSignedPresentation(key,{session_id:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,client_id:anchor.clientId,device_id:"device-A",sequence:1,challenge:ch1.challenge,timestamp:new Date(now1).toISOString()});
const p1=executeSessionContinuityDecision({anchor,durableState:state,presented:{sessionId:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,clientId:anchor.clientId,deviceId:"device-A",sequence:1},signedPresentation:s1,timestamp:new Date(now1).toISOString(),nowMs:now1,signingIdentity:authority.signer,durableTrustStore:trust,outputRoot:path.join(root,"proof-1")});
if(p1.decision!=="ALLOW")throw new Error("P1_NOT_ACCEPTED");
fs.cpSync(source,branchA,{recursive:true});
fs.cpSync(source,branchB,{recursive:true});
const acceptBranch=async(directory,device,now)=>{const st=createSecureSessionState(directory,60000);const ch=issueChallenge(st,anchor.sessionId,now,60000);const signed=createSignedPresentation(key,{session_id:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,client_id:anchor.clientId,device_id:device,sequence:2,challenge:ch.challenge,timestamp:new Date(now).toISOString()});return executeSessionContinuityDecision({anchor,durableState:st,presented:{sessionId:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,clientId:anchor.clientId,deviceId:device,sequence:2},signedPresentation:signed,timestamp:new Date(now).toISOString(),nowMs:now,signingIdentity:authority.signer,durableTrustStore:trust,outputRoot:path.join(root,device==="device-A"?"proof-2A":"proof-2B")});};
const a=await acceptBranch(branchA,"device-A",1700000001000);
const b=await acceptBranch(branchB,"device-A",1700000002000);
const forked=JSON.stringify(a.provenanceCertificate)!==JSON.stringify(b.provenanceCertificate);
console.log("=== CURRENT PRODUCT FORK BASELINE ===");
console.log("P1="+p1.decision);
console.log("P2A="+a.decision);
console.log("P2B="+b.decision);
console.log("P2_CERTIFICATES_DIFFER="+(forked?"YES":"NO"));
console.log("P2A_LOCAL_ACCEPT="+(a.decision==="ALLOW"?"YES":"NO"));
console.log("P2B_LOCAL_ACCEPT="+(b.decision==="ALLOW"?"YES":"NO"));
console.log("CURRENT_PRODUCT_ALTERNATE_BRANCHES_ACCEPTED="+(a.decision==="ALLOW"&&b.decision==="ALLOW"&&forked?"YES":"NO"));
fs.rmSync(root,{recursive:true,force:true});
