import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import crypto from "node:crypto";
import { provisionSigningAuthority } from "../../src/evidence/signing-authority.js";
import { createBindingKey, createSignedPresentation } from "../../src/core/proof-of-possession.js";
import { createSecureSessionState, issueChallenge } from "../../src/core/durable-secure-session-state.js";
import { createDurableTrustStore } from "../../src/evidence/durable-trust-store.js";
import { createOidcSessionAnchor } from "../../src/adapters/oidc-session-adapter.js";
import { executeSessionContinuityDecision } from "../../src/product/session-continuity-decision.js";
import { verifySessionProvenanceReceipt } from "../../src/evidence/session-provenance-receiver.js";

const root=fs.mkdtempSync(path.join(os.tmpdir(),"source-gone-integration-"));
const sourceRoot=path.join(root,"source-app");
const portable=path.join(root,"portable-receipt");
fs.mkdirSync(sourceRoot,{recursive:true});
fs.mkdirSync(portable,{recursive:true});
const authority=provisionSigningAuthority(path.join(sourceRoot,"authority"),{label:"source-gone"});
const trust=createDurableTrustStore(authority.trustRoot);
const state=createSecureSessionState(path.join(sourceRoot,"session-state"),60000);
const key=createBindingKey();
const claims={sub:"source-gone-user",iss:"https://issuer.example",sid:"source-gone-session",auth_time:"2026-09-15T03:00:00.000Z",aud:"source-gone-client"};
const anchorBase=createOidcSessionAnchor({verifiedClaims:claims,clientId:"source-gone-client",deviceId:"device-A"});
const anchor={...anchorBase,publicKeySpkiBase64:key.publicKeySpkiBase64,publicKeyFingerprintSha256:key.publicKeyFingerprint};
const now=Date.now();
const timestamp=new Date(now).toISOString();
const challenge=issueChallenge(state,anchor.sessionId,now,60000);
const signed=createSignedPresentation(key,{session_id:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,client_id:anchor.clientId,device_id:"device-A",sequence:1,challenge:challenge.challenge,timestamp});
const decision=executeSessionContinuityDecision({anchor,durableState:state,presented:{sessionId:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,clientId:anchor.clientId,deviceId:"device-A",sequence:1},signedPresentation:signed,timestamp,nowMs:now,signingIdentity:authority.signer,durableTrustStore:trust,outputRoot:path.join(sourceRoot,"proof")});
if(decision.decision!=="ALLOW")throw new Error("PRODUCT_DID_NOT_ALLOW");
const cert=decision.provenanceCertificate;
const proofRoot=path.join(sourceRoot,"proof");
fs.cpSync(path.join(proofRoot,"bundle"),path.join(portable,"bundle"),{recursive:true});
fs.cpSync(path.join(proofRoot,"lineage"),path.join(portable,"lineage"),{recursive:true});
fs.cpSync(authority.trustRoot,path.join(portable,"trust"),{recursive:true});
fs.writeFileSync(path.join(portable,"certificate.json"),JSON.stringify(cert,null,2),"utf8");
fs.writeFileSync(path.join(portable,"policy.json"),JSON.stringify(decision.policy,null,2),"utf8");
const H=x=>crypto.createHash("sha256").update(JSON.stringify(x)).digest("hex");
const rootId=H({type:"CONTINUITY_ROOT",session_id:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer});
const certHash=H(cert);
const continuityHash=H({continuity_root:rootId,sequence:cert.sequence,parent_hash:"",proof_hash:certHash});
const witness=crypto.generateKeyPairSync("ed25519");
const receiptBody={witness_schema:"continuity-witness.receipt.v1",continuity_root:rootId,sequence:cert.sequence,parent_hash:"",continuity_hash:continuityHash,observed_proof_hash:certHash,witness_head_hash:continuityHash,witness_public_key_spki_base64:witness.publicKey.export({type:"spki",format:"der"}).toString("base64")};
const receipt={body:receiptBody,signature:crypto.sign(null,Buffer.from(JSON.stringify(receiptBody)),witness.privateKey).toString("base64")};
fs.writeFileSync(path.join(portable,"witness-receipt.json"),JSON.stringify(receipt,null,2),"utf8");
fs.rmSync(sourceRoot,{recursive:true,force:true});
const portableTrust=createDurableTrustStore(path.join(portable,"trust"));
const portableCert=JSON.parse(fs.readFileSync(path.join(portable,"certificate.json"),"utf8"));
const portablePolicy=JSON.parse(fs.readFileSync(path.join(portable,"policy.json"),"utf8"));
const portableReceipt=JSON.parse(fs.readFileSync(path.join(portable,"witness-receipt.json"),"utf8"));
const received=verifySessionProvenanceReceipt({certificate:portableCert,durableTrustStore:portableTrust,bundleDir:path.join(portable,"bundle"),lineageDir:path.join(portable,"lineage"),policyDecision:portablePolicy,expectedSessionId:portableCert.session_id,expectedSubject:portableCert.subject,expectedIssuer:portableCert.issuer});
const witnessPublicKey=crypto.createPublicKey({key:Buffer.from(portableReceipt.body.witness_public_key_spki_base64,"base64"),type:"spki",format:"der"});
const witnessSigValid=crypto.verify(null,Buffer.from(JSON.stringify(portableReceipt.body)),witnessPublicKey,Buffer.from(portableReceipt.signature,"base64"));
const receiptBindingOk=portableReceipt.body.observed_proof_hash===H(portableCert)&&portableReceipt.body.continuity_hash===H({continuity_root:portableReceipt.body.continuity_root,sequence:portableReceipt.body.sequence,parent_hash:portableReceipt.body.parent_hash,proof_hash:portableReceipt.body.observed_proof_hash});
console.log("=== SOURCE APP GONE :: REAL PRODUCT INTEGRATION ===");
console.log("PRODUCT_DECISION=ALLOW");
console.log("SOURCE_APP_STATE=DELETED");
console.log("INDEPENDENT_CERT_VERIFY="+(received.verified?"PASS":"FAIL"));
console.log("WITNESS_RECEIPT_SIGNATURE="+(witnessSigValid?"PASS":"FAIL"));
console.log("WITNESS_RECEIPT_BINDING="+(receiptBindingOk?"PASS":"FAIL"));
console.log("PORTABLE_PACKAGE_ONLY="+(received.verified&&witnessSigValid&&receiptBindingOk?"PASS":"FAIL"));
console.log("SOURCE_APP_GONE_RESULT="+(received.verified&&witnessSigValid&&receiptBindingOk?"PASS":"FAIL"));
fs.rmSync(root,{recursive:true,force:true});
