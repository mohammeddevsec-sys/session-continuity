import crypto from "node:crypto";
const {privateKey,publicKey}=crypto.generateKeyPairSync("ed25519");
const canon=x=>JSON.stringify(x);
const H=x=>crypto.createHash("sha256").update(canon(x)).digest("hex");
const sign=x=>crypto.sign(null,Buffer.from(canon(x)),privateKey).toString("base64");
const verify=(x,s)=>crypto.verify(null,Buffer.from(canon(x)),publicKey,Buffer.from(s,"base64"));
const root=H({type:"CONTINUITY_ROOT",session_id:"S1",subject:"U1",issuer:"I1",auth_origin:"A1"});
const coreOf=body=>({schema:body.schema,continuity_root:body.continuity_root,sequence:body.sequence,parent_hash:body.parent_hash,state_hash:body.state_hash,decision_hash:body.decision_hash}); const makeProof=(sequence,parent,state,decision="ALLOW")=>{const core={schema:"continuity-proof.v1.1",continuity_root:root,sequence,parent_hash:parent,state_hash:H(state),decision_hash:H({decision,policy:"P1"})};const body={...core,continuity_hash:H(core)};return {body,signature:sign(body)};};
const verifyProof=p=>{if(!verify(p.body,p.signature))return "INVALID_SIGNATURE";if(p.body.continuity_hash!==H(coreOf(p.body)))return "CONTINUITY_HASH_MISMATCH";if(p.body.continuity_root!==root)return "ROOT_MISMATCH";return "VALID";};
const verifyChain=chain=>{if(!Array.isArray(chain)||chain.length===0)return "EMPTY_CHAIN";for(let i=0;i<chain.length;i++){const p=chain[i];const basic=verifyProof(p);if(basic!=="VALID")return basic;if(p.body.sequence!==i+1)return "SEQUENCE_GAP";if(i===0){if(p.body.parent_hash!=="")return "FIRST_PARENT_INVALID";}else{if(p.body.parent_hash!==chain[i-1].body.continuity_hash)return "PARENT_MISMATCH";}}return "CONTINUITY_PROVEN";};
const witness=()=>{let head=null;return {submit(p){const v=verifyProof(p);if(v!=="VALID")return v;if(!head){if(p.body.sequence!==1)return "FIRST_SEQUENCE_REQUIRED";head=p;return "REGISTERED";}if(p.body.continuity_root!==head.body.continuity_root)return "ROOT_MISMATCH";if(p.body.sequence<head.body.sequence)return "ROLLBACK";if(p.body.sequence===head.body.sequence)return p.body.continuity_hash===head.body.continuity_hash?"IDEMPOTENT_REPLAY":"EQUIVOCATION_FORK";if(p.body.sequence!==head.body.sequence+1)return "SEQUENCE_GAP";if(p.body.parent_hash!==head.body.continuity_hash)return "PARENT_MISMATCH";head=p;return "ADVANCED";}}};
const p1=makeProof(1,"",{device:"D1"});
const p2=makeProof(2,p1.body.continuity_hash,{device:"D1"});
const p2Alt=makeProof(2,p1.body.continuity_hash,{device:"ATTACKED"});
const p3=makeProof(3,p2.body.continuity_hash,{device:"D1"});
const p3Alt=makeProof(3,p2Alt.body.continuity_hash,{device:"ATTACKED"});
const p4=makeProof(5,p3.body.continuity_hash,{device:"D1"});
const forged={body:{...p3.body,state_hash:"FORGED"},signature:p3.signature};
const w=witness();
const w1=w.submit(p1);
const w2=w.submit(p2);
const wFork=w.submit(p2Alt);
const w3=w.submit(p3);
const wGap=w.submit(p4);
const validChain=verifyChain([p1,p2,p3]);
const gapChain=verifyChain([p1,p3]);
const parentSwap=verifyChain([p1,p2Alt,p3]);
const validAltChain=verifyChain([p1,p2Alt,p3Alt]);
const reordered=verifyChain([p1,p3,p2]);
const forgedResult=verifyChain([p1,p2,forged]);
console.log("=== PARENT-BOUND CONTINUITY PROOF V1.1 ===");
console.log("WITNESS_NORMAL="+[w1,w2,w3].join("|"));
console.log("WITNESS_FORK="+wFork);
console.log("WITNESS_GAP="+wGap);
console.log("VALID_CHAIN="+validChain);
console.log("GAP_CHAIN="+gapChain);
console.log("PARENT_SWAP="+parentSwap);
console.log("ALTERNATE_VALID_CHAIN="+validAltChain);
console.log("REORDERED_CHAIN="+reordered);
console.log("FORGED_CHAIN="+forgedResult);
console.log("NORMAL_CHAIN="+(validChain==="CONTINUITY_PROVEN"?"PASS":"FAIL"));
console.log("WITNESS_FORK_PROTECTION="+(wFork==="EQUIVOCATION_FORK"?"PASS":"FAIL"));
console.log("WITNESS_GAP_PROTECTION="+(wGap==="SEQUENCE_GAP"?"PASS":"FAIL"));
console.log("HISTORICAL_GAP_PROTECTION="+(gapChain==="SEQUENCE_GAP"?"PASS":"FAIL"));
console.log("PARENT_SWAP_PROTECTION="+(parentSwap==="PARENT_MISMATCH"?"PASS":"FAIL"));
console.log("ORDER_PROTECTION="+(reordered==="SEQUENCE_GAP"?"PASS":"FAIL"));
console.log("FORGERY_PROTECTION="+(forgedResult==="INVALID_SIGNATURE"?"PASS":"FAIL"));
console.log("ALTERNATE_BRANCH_IS_LOCALLY_VALID="+(validAltChain==="CONTINUITY_PROVEN"?"YES":"NO"));
console.log("REFERENCE_MODEL_V1_1="+(["CONTINUITY_PROVEN","EQUIVOCATION_FORK","SEQUENCE_GAP","SEQUENCE_GAP","PARENT_MISMATCH","SEQUENCE_GAP","INVALID_SIGNATURE"].every((x,i)=>[validChain,wFork,wGap,gapChain,parentSwap,reordered,forgedResult][i]===x)?"PASS":"FAIL"));
