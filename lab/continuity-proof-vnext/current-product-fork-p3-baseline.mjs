import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import crypto from "node:crypto";
import { provisionSigningAuthority } from "../../src/evidence/signing-authority.js";
import { createBindingKey, createSignedPresentation } from "../../src/core/proof-of-possession.js";
import { createSecureSessionState, issueChallenge } from "../../src/core/durable-secure-session-state.js";
import { createDurableTrustStore } from "../../src/evidence/durable-trust-store.js";
import { createOidcSessionAnchor } from "../../src/adapters/oidc-session-adapter.js";
import { executeSessionContinuityDecision } from "../../src/product/session-continuity-decision.js";
import { verifySessionProvenanceReceipt } from "../../src/evidence/session-provenance-receiver.js";
const root=fs.mkdtempSync(path.join(os.tmpdir(),"fork-baseline-p3-"));
const authority=provisionSigningAuthority(path.join(root,"authority"),{label:"fork-baseline-p3"});
const trust=createDurableTrustStore(authority.trustRoot);
const key=createBindingKey();
const claims={sub:"fork-user",iss:"https://issuer.example",sid:"fork-session",auth_time:"2026-09-15T03:00:00.000Z",aud:"fork-client"};
const anchorBase=createOidcSessionAnchor({verifiedClaims:claims,clientId:"fork-client",deviceId:"device-A"});
const anchor={...anchorBase,publicKeySpkiBase64:key.publicKeySpkiBase64,publicKeyFingerprintSha256:key.publicKeyFingerprint};
const p1Dir=path.join(root,"state-p1");
const aDir=path.join(root,"branch-A");
const bDir=path.join(root,"branch-B");
const accept=({directory,sequence,now,label})=>{const st=createSecureSessionState(directory,60000);const ch=issueChallenge(st,anchor.sessionId,now,60000);const ts=new Date(now).toISOString();const signed=createSignedPresentation(key,{session_id:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,client_id:anchor.clientId,device_id:"device-A",sequence,challenge:ch.challenge,timestamp:ts});const result=executeSessionContinuityDecision({anchor,durableState:st,presented:{sessionId:anchor.sessionId,subject:anchor.subject,issuer:anchor.issuer,clientId:anchor.clientId,deviceId:"device-A",sequence},signedPresentation:signed,timestamp:ts,nowMs:now,signingIdentity:authority.signer,durableTrustStore:trust,outputRoot:path.join(root,label)});return result;};
const p1=accept({directory:p1Dir,sequence:1,now:1700000000000,label:"proof-1"});
if(p1.decision!=="ALLOW")throw new Error("P1_NOT_ACCEPTED");
fs.cpSync(p1Dir,aDir,{recursive:true});
fs.cpSync(p1Dir,bDir,{recursive:true});
const p2a=accept({directory:aDir,sequence:2,now:1700000001000,label:"proof-2A"});
const p2b=accept({directory:bDir,sequence:2,now:1700000002000,label:"proof-2B"});
const p3a=accept({directory:aDir,sequence:3,now:1700000003000,label:"proof-3A"});
const p3b=accept({directory:bDir,sequence:3,now:1700000004000,label:"proof-3B"});
for(const x of [p2a,p2b,p3a,p3b])if(x.decision!=="ALLOW")throw new Error("BRANCH_ACCEPTANCE_FAILED");
const certs={p1:p1.provenanceCertificate,p2a:p2a.provenanceCertificate,p2b:p2b.provenanceCertificate,p3a:p3a.provenanceCertificate,p3b:p3b.provenanceCertificate};
const H=x=>crypto.createHash("sha256").update(JSON.stringify(x)).digest("hex");
const certHash=x=>H(x);
const verifyResult=(result,label)=>{const c=result.provenanceCertificate;const dir=path.join(root,label);return verifySessionProvenanceReceipt({certificate:c,durableTrustStore:trust,bundleDir:path.join(dir,"bundle"),lineageDir:path.join(dir,"lineage"),policyDecision:result.policy,expectedSessionId:c.session_id,expectedSubject:c.subject,expectedIssuer:c.issuer});};
const v2a=verifyResult(p2a,"proof-2A");
const v2b=verifyResult(p2b,"proof-2B");
const v3a=verifyResult(p3a,"proof-3A");
const v3b=verifyResult(p3b,"proof-3B");
const p2Different=certHash(certs.p2a)!==certHash(certs.p2b);
const p3Different=certHash(certs.p3a)!==certHash(certs.p3b);
const hasParentField=c=>Object.prototype.hasOwnProperty.call(c,"parent_hash")||Object.prototype.hasOwnProperty.call(c,"previous_proof_hash");
console.log("=== CURRENT PRODUCT FORK BASELINE V3 ===");
console.log("P1="+p1.decision);
console.log("P2A="+p2a.decision);
console.log("P2B="+p2b.decision);
console.log("P3A="+p3a.decision);
console.log("P3B="+p3b.decision);
console.log("BRANCH_A_SEQUENCE="+certs.p2a.sequence+"->"+certs.p3a.sequence);
console.log("BRANCH_B_SEQUENCE="+certs.p2b.sequence+"->"+certs.p3b.sequence);
console.log("P2_CERTIFICATES_DIFFER="+(p2Different?"YES":"NO"));
console.log("P3_CERTIFICATES_DIFFER="+(p3Different?"YES":"NO"));
console.log("P2A_LOCAL_PROOF="+(v2a.verified?"PASS":"FAIL"));
console.log("P2B_LOCAL_PROOF="+(v2b.verified?"PASS":"FAIL"));
console.log("P3A_LOCAL_PROOF="+(v3a.verified?"PASS":"FAIL"));
console.log("P3B_LOCAL_PROOF="+(v3b.verified?"PASS":"FAIL"));
console.log("PROVENANCE_PARENT_FIELD_PRESENT="+([certs.p2a,certs.p2b,certs.p3a,certs.p3b].some(hasParentField)?"YES":"NO"));
console.log("DIVERGENCE_POINT=P1");
console.log("DIVERGENCE_LEVEL=2");
console.log("TWO_LOCALLY_VALID_HISTORIES="+(p2Different&&p3Different&&v2a.verified&&v2b.verified&&v3a.verified&&v3b.verified?"YES":"NO"));
console.log("CURRENT_PRODUCT_HISTORICAL_EQUIVOCATION_PROOF="+(p2Different&&p3Different&&v2a.verified&&v2b.verified&&v3a.verified&&v3b.verified&&![certs.p2a,certs.p2b,certs.p3a,certs.p3b].some(hasParentField)?"BASELINE_CONFIRMED":"NOT_CONFIRMED"));
fs.rmSync(root,{recursive:true,force:true});
