import crypto from "node:crypto";
const {privateKey,publicKey}=crypto.generateKeyPairSync("ed25519");
const root="AUTH-ROOT-MODEL";
const canon=x=>JSON.stringify(x);
const hash=x=>crypto.createHash("sha256").update(canon(x)).digest("hex");
const sign=b=>crypto.sign(null,Buffer.from(canon(b)),privateKey).toString("base64");
const verify=p=>crypto.verify(null,Buffer.from(canon(p.body)),publicKey,Buffer.from(p.sig,"base64"));
const make=(sequence,parent,state=root)=>{const body={root,sequence,parent,state};return {body,sig:sign(body)};};
function witness(){let head=null; return {submit(p){if(!verify(p))return {ok:false,reason:"INVALID_SIGNATURE"}; if(!head){if(p.body.sequence!==1)return {ok:false,reason:"FIRST_SEQUENCE_REQUIRED"}; head={...p};return {ok:true,reason:"REGISTERED"};} if(p.body.sequence<head.body.sequence)return {ok:false,reason:"ROLLBACK"}; if(p.body.sequence===head.body.sequence){return hash(p.body)===hash(head.body)?{ok:true,reason:"IDEMPOTENT_REPLAY"}:{ok:false,reason:"EQUIVOCATION_FORK"};} if(p.body.sequence!==head.body.sequence+1)return {ok:false,reason:"SEQUENCE_GAP"}; if(p.body.parent!==hash(head.body))return {ok:false,reason:"PARENT_MISMATCH"}; head={...p};return {ok:true,reason:"ADVANCED"};}, get(){return head;}}}
const w=witness();
const p1=make(1,"","S1");
const p2=make(2,hash(p1.body),"S2");
const p2fork=make(2,hash(p1.body),"S2-FORK");
const p3=make(3,hash(p2.body),"S3");
const p4gap=make(5,hash(p3.body),"S5");
const p2old=make(2,hash(p1.body),"S2-OLD");
const forged={body:{root,sequence:4,parent:hash(p3.body),state:"FORGED"},sig:"INVALID"};
const r1=w.submit(p1);
const r2=w.submit(p2);
const rf=w.submit(p2fork);
const r3=w.submit(p3);
const rg=w.submit(p4gap);
const rr=w.submit(p2old);
const ri=w.submit(p3);
const rforged=w.submit(forged);
console.log("=== CLEAN IN-MEMORY WITNESS MODEL ===");
console.log("01_FIRST_REGISTER="+r1.reason);
console.log("02_NORMAL_ADVANCE="+r2.reason);
console.log("03_FORK="+rf.reason);
console.log("04_NORMAL_NEXT="+r3.reason);
console.log("05_GAP="+rg.reason);
console.log("06_ROLLBACK="+rr.reason);
console.log("07_IDENTICAL_REPLAY="+ri.reason);
console.log("08_FORGED_SIGNATURE="+rforged.reason);
console.log("FORK_BLOCKED="+(rf.reason==="EQUIVOCATION_FORK"?"PASS":"FAIL"));
console.log("GAP_BLOCKED="+(rg.reason==="SEQUENCE_GAP"?"PASS":"FAIL"));
console.log("ROLLBACK_BLOCKED="+(rr.reason==="ROLLBACK"?"PASS":"FAIL"));
console.log("REPLAY_IDEMPOTENT="+(ri.reason==="IDEMPOTENT_REPLAY"?"PASS":"FAIL"));
console.log("FORGED_BLOCKED="+(rforged.reason==="INVALID_SIGNATURE"?"PASS":"FAIL"));
console.log("HEAD_SEQUENCE="+w.get().body.sequence);
console.log("WITNESS_MODEL_RESULT="+([rf.reason==="EQUIVOCATION_FORK",rg.reason==="SEQUENCE_GAP",rr.reason==="ROLLBACK",ri.reason==="IDEMPOTENT_REPLAY",rforged.reason==="INVALID_SIGNATURE"].every(Boolean)?"PASS":"FAIL"));
