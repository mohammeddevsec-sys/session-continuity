import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const dir=fs.mkdtempSync(path.join(os.tmpdir(),"witness-restart-"));
const file=path.join(dir,"WITNESS.json");
const {privateKey,publicKey}=crypto.generateKeyPairSync("ed25519");
const root="AUTH-ROOT-RESTART";
const canon=x=>JSON.stringify(x);
const hash=x=>crypto.createHash("sha256").update(canon(x)).digest("hex");
const sign=b=>crypto.sign(null,Buffer.from(canon(b)),privateKey).toString("base64");
const verify=p=>crypto.verify(null,Buffer.from(canon(p.body)),publicKey,Buffer.from(p.sig,"base64"));
const make=(sequence,parent,state)=>{const body={root,sequence,parent,state};return {body,sig:sign(body)};};
const read=()=>fs.existsSync(file)?JSON.parse(fs.readFileSync(file,"utf8")):[];
const createWitness=()=>{let rows=read(); return {submit(p){if(!verify(p))return {ok:false,reason:"INVALID_SIGNATURE"}; const last=rows[rows.length-1]; if(!last){if(p.body.sequence!==1)return {ok:false,reason:"FIRST_SEQUENCE_REQUIRED"};} else {if(p.body.sequence<last.body.sequence)return {ok:false,reason:"ROLLBACK"}; if(p.body.sequence===last.body.sequence)return hash(p.body)===hash(last.body)?{ok:true,reason:"IDEMPOTENT_REPLAY"}:{ok:false,reason:"EQUIVOCATION_FORK"}; if(p.body.sequence!==last.body.sequence+1)return {ok:false,reason:"SEQUENCE_GAP"}; if(p.body.parent!==hash(last.body))return {ok:false,reason:"PARENT_MISMATCH"};} rows=[...rows,p]; fs.writeFileSync(file,JSON.stringify(rows,null,2),"utf8"); return {ok:true,reason:"ACCEPTED"};},head:()=>rows[rows.length-1]};};
const w1=createWitness();
const p1=make(1,"","S1");
const p2=make(2,hash(p1.body),"S2");
const r1=w1.submit(p1);
const r2=w1.submit(p2);
const savedHead=hash(w1.head().body);
const w2=createWitness();
const restartOk=w2.head() && hash(w2.head().body)===savedHead;
const p3=make(3,hash(p2.body),"S3");
const r3=w2.submit(p3);
const fork=make(3,hash(p2.body),"S3-FORK");
const gap=make(5,hash(p3.body),"S5");
const rollback=make(1,"","S1-OLD");
const replay=w2.submit(p3);
const rf=w2.submit(fork);
const rg=w2.submit(gap);
const rr=w2.submit(rollback);
const forged={body:{root,sequence:4,parent:hash(p3.body),state:"FORGED"},sig:"BAD"};
const rforged=w2.submit(forged);
console.log("=== WITNESS RESTART CONTINUITY LAB ===");
console.log("P1="+r1.reason);
console.log("P2="+r2.reason);
console.log("RESTART_HEAD_RECOVERED="+(restartOk?"YES":"NO"));
console.log("P3_AFTER_RESTART="+r3.reason);
console.log("IDENTICAL_REPLAY="+replay.reason);
console.log("FORK_AFTER_RESTART="+rf.reason);
console.log("GAP_AFTER_RESTART="+rg.reason);
console.log("ROLLBACK_AFTER_RESTART="+rr.reason);
console.log("FORGED_AFTER_RESTART="+rforged.reason);
console.log("RESTART_RECOVERY="+(restartOk&&r3.reason==="ACCEPTED"?"PASS":"FAIL"));
console.log("FORK_BLOCKED="+(rf.reason==="EQUIVOCATION_FORK"?"PASS":"FAIL"));
console.log("GAP_BLOCKED="+(rg.reason==="SEQUENCE_GAP"?"PASS":"FAIL"));
console.log("ROLLBACK_BLOCKED="+(rr.reason==="ROLLBACK"?"PASS":"FAIL"));
console.log("REPLAY_IDEMPOTENT="+(replay.reason==="IDEMPOTENT_REPLAY"?"PASS":"FAIL"));
console.log("FORGED_BLOCKED="+(rforged.reason==="INVALID_SIGNATURE"?"PASS":"FAIL"));
console.log("WITNESS_RESTART_RESULT="+([restartOk,r3.reason==="ACCEPTED",rf.reason==="EQUIVOCATION_FORK",rg.reason==="SEQUENCE_GAP",rr.reason==="ROLLBACK",replay.reason==="IDEMPOTENT_REPLAY",rforged.reason==="INVALID_SIGNATURE"].every(Boolean)?"PASS":"FAIL"));
fs.rmSync(dir,{recursive:true,force:true});
